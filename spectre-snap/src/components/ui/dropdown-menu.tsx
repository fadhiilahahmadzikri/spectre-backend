function DropdownMenuItem({
  className,
  inset,
  variant = "default",
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Item> & {
  inset?: boolean
  variant?: "default" | "destructive"
}) {
  return (
    <DropdownMenuPrimitive.Item
      data-slot="dropdown-menu-item"
      data-inset={inset}
      data-variant={variant}
      className={cn(
        "relative flex cursor-default select-none items-center gap-2 rounded-[6px] px-2 py-1.5 text-[12px] outline-none transition-colors",
        "focus:bg-[color:var(--fill-tertiary)] focus:text-[color:var(--label-primary)]",
        "data-[disabled]:pointer-events-none data-[disabled]:opacity-50",
        "data-[variant=destructive]:text-[color:var(--sys-red,#ff453a)] data-[variant=destructive]:focus:bg-[rgba(255,69,58,0.12)] data-[variant=destructive]:focus:text-[color:var(--sys-red,#ff453a)]",
        "[&_svg]:size-3.5 [&_svg]:shrink-0 [&_svg:not([class*='text-'])]:text-current",
        inset && "pl-8",
        className
      )}
      {...props}
    />
  )
}

